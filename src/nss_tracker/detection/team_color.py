"""VS画面(マッチング完了直後)での自チーム/相手チームの色のサンプリング。

VS画面では自チーム・相手チームそれぞれの名前タグ背景が丸ごとチームカラー
(青系/ピンク系等)で塗りつぶされている。「青/赤/ピンク」のような固定色への
分類はせず、実際に描画されている色をそのまま平均RGBでサンプリングしてhex
文字列(例: "#64bde2")として返す(色閾値による分類ロジックを作らずに済み、
分類誤りのリスクも無いため。用途がWebダッシュボードでの装飾表示のみで、
勝敗判定等のロジックには使わないことからもこの方式で十分)。

サンプリング領域はvs_rank.pyと同じスロット0(画面手前、常に表示される選手)の
名前タグバーのうち、文字やランクバッジが重ならない右寄りの帯を使う。

Issue #144対応: 当初のROI(x幅250px×高さ9px、名前タグバーの下端寄りを横断する
細長い帯)は、実際には(1)名前文字のアンチエイリアス縁が上端付近にわずかに
かぶる、(2)バー自体が単色ではなく左右方向にグラデーションで塗られており
場所によって色が変わる、という2つの問題があることが実データで判明した(86番
`86_matching_with_rank_4v4_hdr_off.png`のピクセル値を直接確認して発覚)。
名前の長さに関わらず名前タグの丸い右端(グラデーションが収束し、文字も
被らない)まで届く位置に、幅20px×高さ18pxの小さな矩形を置くよう変更した。
86番・82番(`82_matching_with_rank_4v3_hdr_off.png`、別試合)の両方で標準偏差が
2未満(旧ROIは18〜72)の完全に均一な色になることを確認済み。

Issue #424対応: このROIは**ランクバッジありのレイアウトを前提にした固定位置**であり、
ランクバッジが表示されない試合では名前タグ全体が約42px左に寄るため、ROIがバーの
右外(芝生)に落ちる。実測ではバーの右端が「バッジあり=469 / バッジなし=427」に対し
ROIが441〜461のため、バッジが無いと完全に外れる。バッジありの場合も余裕は8pxしかない。
fixtures/screenshots/72・73・87(いずれも野良のバッジ無しVS画面)と、2026-09-08の専用部屋
配信の実フレームすべてで再現する。

このときはROI自体を修正せず、表示側(`web/server.py`の`_normalize_team_color()`)で
色相ベースの「青系/ピンク系」分類を行うことで、ROIがずれても「正しい色」か「灰色」の
どちらかにしか倒れないようにした(青とピンクを取り違えないことは実測色の混合で確認済み)。

Issue #494対応: 専用部屋の配信では毎試合灰色になっていたため、ROIを名前タグの**左端寄り**へ
移した(自チーム x141〜148、相手チーム x1505〜1509、y868〜888/889)。名前タグはバッジの
有無で右端の位置が変わる一方、左端寄りの位置はバッジあり・なしの両方でタグの内側に入る。
**値はユーザーが自分で検証したもの**(Claudeは候補値を出さない、ユーザーとの相談で決定)。
fixtures/screenshots/72・73・87(バッジなし)・82・86(バッジあり)の5枚で、自チームは
青系(色相200〜208度)・相手チームはピンク系(324〜334度)、ROI内のRGB標準偏差は最大6.2で
芝生等は混ざっていない。上下左右に3pxずらしても分類は変わらない。注意点:
- バッジありの試合では、相手チームのROIの左端からタグの丸い左端まで2px程度しかない。
  下端のy888の行もタグの縁(色が薄くなる部分)に少しかかる
- 名前タグは左から右へのグラデーションのため、右端を測っていた以前より濃い色が
  記録される(例: 青は以前の`#20d0f6`前後に対し`#49bdf9`前後)。分類の帯には収まっている
- 名前の文字はタグの上半分に中央寄せで重なる。手元の画像では文字はROIのずっと右で
  止まっているが、非常に長い名前で左端まで伸びるかは未確認

本モジュール自体は従来どおり**実測した生の色をそのまま返す**(分類は行わない)。DBにも
生の値がそのまま保存されるため、将来分類の帯を見直したくなった場合は保存済みの値から
再判定できる。
"""

import numpy as np

from nss_tracker.detection_config import get_detection_value

# (x1, y1, x2, y2)。名前タグバーの左端寄り、ランクバッジの有無によらずタグの内側に
# 入る位置(Issue #494、ユーザー検証値。モジュールdocstring参照)
MINE_ROI = get_detection_value("team_color", "MINE_ROI", (141, 868, 148, 888))
OPPONENT_ROI = get_detection_value("team_color", "OPPONENT_ROI", (1505, 868, 1509, 889))


def _average_hex(frame: np.ndarray, roi: tuple[int, int, int, int]) -> str:
    x1, y1, x2, y2 = roi
    crop = frame[y1:y2, x1:x2]
    if crop.size == 0:
        # 想定解像度(1920x1080)より小さいフレームが渡された場合(テスト用の
        # ダミーフレーム等)にROIがフレーム範囲外になるとcropが空になり、
        # 平均計算がnanになってクラッシュする。実運用では起こらない想定だが、
        # 呼び出し側を落とさないためニュートラルな黒を返す
        return "#000000"
    b, g, r = crop.reshape(-1, 3).mean(axis=0)
    return f"#{int(round(r)):02x}{int(round(g)):02x}{int(round(b)):02x}"


def read_team_colors(frame: np.ndarray) -> tuple[str, str]:
    """VS画面のフレームから(自チームの色, 相手チームの色)をhex文字列で返す。"""
    return _average_hex(frame, MINE_ROI), _average_hex(frame, OPPONENT_ROI)
